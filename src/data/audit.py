def rate_table(p: pd.DataFrame, by: str, ycol="y", stcol="label_status") -> pd.DataFrame:
    ok = p[stcol] == "ok"
    g = p.groupby(by, dropna=False)
    t = pd.DataFrame({"rows": g.size(), "firms": g["id"].nunique()})
    t["usable_rows"] = p[ok].groupby(by, dropna=False).size()
    t["defaults"] = p[ok].groupby(by, dropna=False)[ycol].sum()
    t["default_rate"] = t["defaults"] / t["usable_rows"]
    t = t.fillna(0)
    t.index = pd.Index(["missing" if pd.isna(i) else i for i in t.index], name=by)
    for c in ["rows", "firms", "usable_rows", "defaults"]:
        t[c] = t[c].astype(int)
    return t


def close(a, b, tol=0.01):
    m = a.notna() & b.notna()
    hit = ((a - b).abs() <= tol * np.maximum(a.abs(), b.abs())) | ((a - b).abs() <= 2)  # 1% or EUR 2 rounding
    return int(m.sum()), float((hit & m).sum() / max(m.sum(), 1))


