"""Missingness study -> reports/data/02_missingness.md (+ csv). Run after build_panel.

python -m src.data.missingness
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from src.data.load_raw import NUM_COLS  # noqa: E402
from src.data.mdutil import md  # noqa: E402

REP = ROOT / "reports/data"
ST = ["debt_bank_st", "debt_fin_st", "AP_st"]
LT = ["debt_bank_lt", "debt_fin_lt", "AP_lt"]
SIZE_BINS = [1.5e6, 2e6, 3e6, 4e6, 4.5e6, 5e6, 6e6, 8e6, 10e6, 20e6, 50e6, np.inf]
SIZE_LABELS = ["1.5-2M", "2-3M", "3-4M", "4-4.5M", "4.5-5M", "5-6M", "6-8M", "8-10M", "10-20M", "20-50M", ">50M"]
REV_BINS = [-np.inf, 0, 2e6, 4e6, 6e6, 8e6, 9e6, 10e6, 20e6, np.inf]
REV_LABELS = ["<=0", "0-2M", "2-4M", "4-6M", "6-8M", "8-9M", "9-10M", "10-20M", ">20M"]


def close(a, b, tol=0.01):
    return ((a - b).abs() <= tol * np.maximum(a.abs(), b.abs())) | ((a - b).abs() <= 2)


def main():
    p = pd.read_parquet(ROOT / "data/interim/panel.parquet")
    ok = p["label_status"] == "ok"
    base = p.loc[ok, "y"].mean()
    L = []
    P = L.append
    P("# 02 Missingness study\n")
    P("Generated by `src/data/missingness.py` from `data/interim/panel.parquet`. Default rates use the primary label "
      f"(start 6m, usable rows fs_year 2007-2010; base rate {base:.4f}). Missing = NaN after unified NA handling "
      "(training file: empty cells only).\n")

    # ---- 1 per field, per year
    miss_cols = [c for c in NUM_COLS + ["HQ_city", "legal_struct", "ateco_sector"] if p[c].isna().any()]
    t = p.groupby("fs_year")[miss_cols].apply(lambda g: g.isna().mean()).T
    t.insert(0, "all_years", p[miss_cols].isna().mean())
    t.insert(0, "n_missing", p[miss_cols].isna().sum().astype(int))
    t = t.sort_values("n_missing", ascending=False)
    t.to_csv(REP / "miss_by_field_year.csv")
    P("## 1. Missing rate per field, overall and by fs_year\n")
    P(f"Fields never missing: {[c for c in NUM_COLS + ['id','fs_year','stmt_date','HQ_city','legal_struct','ateco_sector'] if not p[c].isna().any()]}.\n")
    P(md(t, ".4f"))

    # ---- 2 co-missing patterns
    P("\n## 2. Co-missing blocks\n")
    pat = p[ST + LT].isna()
    key = pat.apply(lambda r: "".join("M" if v else "." for v in r), axis=1) if len(p) < 0 else (
        pat.astype(int).astype(str).agg("".join, axis=1).str.replace("1", "M").str.replace("0", "."))
    pt = pd.DataFrame({"pattern": key, "y": p["y"], "ok": ok, "asst_tot": p["asst_tot"]})
    g = pt.groupby("pattern")
    PT = pd.DataFrame({"rows": g.size(), "share": g.size() / len(p), "median_asst_tot": g["asst_tot"].median(),
                       "usable": pt[pt.ok].groupby("pattern").size(), "default_rate": pt[pt.ok].groupby("pattern")["y"].mean()})
    PT = PT.sort_values("rows", ascending=False)
    PT.to_csv(REP / "miss_debt_patterns.csv")
    P("Pattern over (" + ", ".join(ST + LT) + "); `M` = missing, `.` = present:\n")
    P(md(PT.head(12), ".4f"))
    st_m, lt_m = pat[ST].all(axis=1), pat[LT].all(axis=1)
    st_any, lt_any = pat[ST].any(axis=1), pat[LT].any(axis=1)
    P(f"\n- Short-term split (3 fields): any missing {st_any.sum():,} rows, all 3 missing {st_m.sum():,} ({st_m.sum()/max(st_any.sum(),1):.1%} of 'any').")
    P(f"- Long-term split (3 fields): any missing {lt_any.sum():,}, all 3 missing {lt_m.sum():,} ({lt_m.sum()/max(lt_any.sum(),1):.1%} of 'any').")
    P(f"- Both blocks fully missing: {(st_m & lt_m).sum():,}. Totals `debt_st`/`debt_lt` present when the ST/LT block is fully missing: "
      f"{p.loc[st_m, 'debt_st'].notna().mean():.2%} / {p.loc[lt_m, 'debt_lt'].notna().mean():.2%}.")
    # correlation of missingness indicators
    ind = p[[c for c in miss_cols if p[c].isna().mean() > 0.001]].isna().astype(float)
    corr = ind.corr().round(2)
    corr.to_csv(REP / "miss_indicator_corr.csv")
    P("\nCorrelation of missing indicators (fields with > 0.1% missing):\n")
    P(md(corr, ".2f"))

    # ---- 3 size / structure
    P("\n## 3. Is missingness structural? (abbreviated statements hypothesis)\n")
    P("Hypothesis H2a: firms below the size limits of Italian Civil Code art. 2435-bis may file an abbreviated balance sheet "
      "(bilancio in forma abbreviata), with the balance sheet shown only at aggregated item level (R-27, current text VERIFIED; the "
      "limits in force 2007-2012, reported as EUR 4.4M assets / 8.8M revenue / 50 employees from 2008, are SECONDARY only). "
      "If abbreviated balance sheets show payables only in total (within / beyond 12 months) [UNVERIFIED detail], the bank/fin/AP split would be "
      "missing while `debt_st`/`debt_lt` are present: the pattern in section 2. The tests below check whether the block's missingness "
      "falls with size and is persistent within firm. Data alone cannot prove the legal mechanism.\n")
    p["size_band"] = pd.cut(p["asst_tot"], SIZE_BINS, labels=SIZE_LABELS, right=False)
    p["rev_band"] = pd.cut(p["rev_operating"], REV_BINS, labels=REV_LABELS)
    p["st_block_missing"], p["lt_block_missing"] = st_m, lt_m
    p["days_rec_missing"], p["roe_missing"], p["margin_fin_missing"] = p["days_rec"].isna(), p["roe"].isna(), p["margin_fin"].isna()
    flags = ["st_block_missing", "lt_block_missing", "days_rec_missing", "roe_missing", "margin_fin_missing"]
    sb = p.groupby("size_band", observed=True)[flags].mean()
    sb.insert(0, "rows", p.groupby("size_band", observed=True).size())
    sb.to_csv(REP / "miss_by_size.csv")
    P("By total-asset band (share of rows missing):\n")
    P(md(sb, ".3f"))
    rb = p.groupby("rev_band", observed=True)[flags].mean()
    rb.insert(0, "rows", p.groupby("rev_band", observed=True).size())
    rb.to_csv(REP / "miss_by_revenue.csv")
    P("\nBy operating-revenue band:\n")
    P(md(rb, ".3f"))
    lsb = p.groupby("legal_struct")[flags].mean()
    lsb.insert(0, "rows", p.groupby("legal_struct").size())
    P("\nBy legal structure:\n")
    P(md(lsb, ".3f"))
    yb = p.groupby("fs_year")[flags].mean()
    P("\nBy fs_year:\n")
    P(md(yb, ".3f"))
    # persistence
    q = p[["id", "fs_year", "st_block_missing"]].sort_values(["id", "fs_year"])
    q["prev"] = q.groupby("id")["st_block_missing"].shift()
    q["prev_year"] = q.groupby("id")["fs_year"].shift()
    q = q[q["prev_year"] == q["fs_year"] - 1]
    pm = q.groupby("prev")["st_block_missing"].mean()
    P(f"\nPersistence: P(ST block missing at t | missing at t-1) = {pm.get(True, np.nan):.3f}; "
      f"P(missing at t | present at t-1) = {pm.get(False, np.nan):.3f} (consecutive firm-years, n = {len(q):,}).")
    yrs_hi = p["fs_year"].isin([2008, 2009, 2010])
    P(f"Vintage effect: ST block missing on {p.loc[yrs_hi, 'st_block_missing'].mean():.1%} of 2008-2010 rows vs "
      f"{p.loc[~yrs_hi, 'st_block_missing'].mean():.1%} of 2007/2011/2012 rows. A size-based filing option alone would not explain a doubling in 2008-2010 followed by a fall in 2011, "
      "so part of the block's missingness is a data-collection (vintage) effect, not only a filing-format effect; the holdout's "
      "missing rate may differ from training.")
    lo_r, hi_r = p["rev_operating"] < 8e6, p["rev_operating"] >= 10e6
    P(f"Revenue gradient: ST block missing on {p.loc[lo_r, 'st_block_missing'].mean():.1%} of rows with revenue < 8M, "
      f"{p.loc[(~lo_r) & (~hi_r), 'st_block_missing'].mean():.1%} at 8-10M and {p.loc[hi_r, 'st_block_missing'].mean():.1%} at >= 10M; "
      "the drop is steeper by revenue than by assets, consistent with (not proof of) a size-limit-based filing option. Large firms "
      "with the block missing still exist, so the mechanism is not purely legal.")
    small = p["asst_tot"] < 4e6
    P(f"ST block missing: {p.loc[small, 'st_block_missing'].mean():.1%} of rows with assets < 4M vs "
      f"{p.loc[p['asst_tot'] >= 10e6, 'st_block_missing'].mean():.1%} with assets >= 10M.")

    # ---- 4 informative?
    P("\n## 4. Is missingness informative? Default rate when missing vs present (H2)\n")
    rows = []
    for c in miss_cols + ["st_block_missing", "lt_block_missing"]:
        m = p[c] if c.endswith("_missing") else p[c].isna()
        mm, pp_ = ok & m, ok & ~m
        if mm.sum() == 0:
            continue
        r_m, r_p = p.loc[mm, "y"].mean(), p.loc[pp_, "y"].mean()
        nmd = int(p.loc[mm, "y"].sum())
        se = np.sqrt(r_m * (1 - r_m) / mm.sum() + r_p * (1 - r_p) / pp_.sum())
        rows.append({"field": c, "usable_missing": int(mm.sum()), "defaults_when_missing": nmd, "rate_missing": r_m,
                     "rate_present": r_p, "ratio": r_m / r_p if r_p > 0 else np.nan,
                     "z": (r_m - r_p) / se if (se > 0 and nmd >= 10) else np.nan})
    I = pd.DataFrame(rows).set_index("field").sort_values("usable_missing", ascending=False)
    I.to_csv(REP / "miss_informative.csv")
    P(md(I, ".4f"))
    P("\n`z` = difference in rates / its standard error (two independent proportions; ignores firm clustering, so treat |z| < 3 as weak). "
      "Fields with < 30 defaults_when_missing are too thin to conclude anything (z not shown below 10 defaults).")
    neg = p["eqty_tot"] < 0
    ct = pd.crosstab(p["margin_fin"].isna(), neg)
    P(f"\nWhy `margin_fin` missingness is so informative: margin_fin is missing on {int((p['margin_fin'].isna() & neg).sum()):,} of "
      f"{int(neg.sum()):,} rows with negative equity and on {int((p['margin_fin'].isna() & ~neg).sum()):,} rows with equity >= 0. "
      "The provider blanks margin_fin when equity is negative, so 'margin_fin missing' is a negative-equity flag (default rate above), "
      "and `roe` missing is a negative-equity-or-|ROE|>=150% flag. Both are fully reconstructable (section 5): the information is in "
      "eqty_tot, not in the missingness itself.")
    # within size band: is block missingness informative after controlling for size?
    w = p[ok].groupby(["size_band", "st_block_missing"], observed=True)["y"].agg(["mean", "size"]).unstack()
    w.columns = [f"{a}_{'missing' if b else 'present'}" for a, b in w.columns]
    w.to_csv(REP / "miss_st_block_by_size_rate.csv")
    P("\nST-block missing vs present, default rate within asset band (controls for size):\n")
    P(md(w, ".4f"))

    # ---- 5 reconstruction
    P("\n## 5. Reconstruction from accounting identities (Roger G2)\n")
    fx = p["asst_intang_fixed"] + p["asst_tang_fixed"] + p["asst_fixed_fin"]
    rec = {
        "margin_fin": (p["eqty_tot"] - fx, "eqty_tot - (intang + tang + fin fixed)"),
        "wc_net": (p["asst_current"] - p["debt_st"], "asst_current - debt_st"),
        "prof_operations": (p["rev_operating"] - p["COGS"], "rev_operating - COGS"),
        "rev_operating": (p["prof_operations"] + p["COGS"], "prof_operations + COGS"),
        "COGS": (p["rev_operating"] - p["prof_operations"], "rev_operating - prof_operations"),
        "roa": (100 * p["prof_operations"] / p["asst_tot"], "100 * prof_operations / asst_tot"),
        "roe": (100 * p["profit"] / p["eqty_tot"], "100 * profit / eqty_tot (no truncation)"),
        "cf_operations": (p["profit"] + p["ebitda"] - p["prof_operations"], "profit + ebitda - prof_operations"),
        "ebitda": (p["cf_operations"] - p["profit"] + p["prof_operations"], "cf_operations - profit + prof_operations"),
        "profit": (p["cf_operations"] - p["ebitda"] + p["prof_operations"], "cf_operations - ebitda + prof_operations"),
        "debt_st": (p["asst_current"] - p["wc_net"], "asst_current - wc_net"),
        "asst_current": (p["wc_net"] + p["debt_st"], "wc_net + debt_st"),
        "eqty_tot": (p["margin_fin"] + fx, "margin_fin + fixed assets"),
        "asst_tang_fixed": (p["asst_tot"] - p["asst_intang_fixed"] - p["asst_fixed_fin"] - p["asst_current"], "asst_tot - other 3 components (approx.: omits residual asset item)"),
        "asst_intang_fixed": (p["asst_tot"] - p["asst_tang_fixed"] - p["asst_fixed_fin"] - p["asst_current"], "asst_tot - other 3 components (approx.)"),
        "asst_fixed_fin": (p["asst_tot"] - p["asst_tang_fixed"] - p["asst_intang_fixed"] - p["asst_current"], "asst_tot - other 3 components (approx.)"),
        "days_rec": (365 * p["AR"] / p["rev_operating"].where(p["rev_operating"] > 0), "365 * AR / rev_operating (a NEW definition; the file's days_rec does not follow it)"),
    }
    rr = []
    for c, (v, f) in rec.items():
        miss = p[c].isna()
        fill = miss & v.notna() & np.isfinite(v)
        pres = p[c].notna() & v.notna() & np.isfinite(v)
        acc = close(v[pres], p.loc[pres, c]).mean() if pres.any() else np.nan
        rr.append({"field": c, "formula": f, "missing": int(miss.sum()), "reconstructable": int(fill.sum()),
                   "share_recovered": fill.sum() / miss.sum() if miss.sum() else np.nan, "accuracy_on_present_rows": acc})
    RR = pd.DataFrame(rr).set_index("field")
    RR.to_csv(REP / "miss_reconstruction.csv")
    P("`accuracy_on_present_rows` = share of rows where the formula reproduces the reported value within 1% (validates the identity).\n")
    P(md(RR, ".4f"))
    _r = 100 * p["profit"] / p["eqty_tot"]
    rr_ = p["roe"].isna() & _r.notna() & np.isfinite(_r)
    P(f"\nNote on `roe`: the formula recovers a value for {int(rr_.sum()):,} missing rows, but these are exactly the rows the provider "
      "blanked because |ROE| >= 150% or equity <= 0 (01_profile.md section 5). A feature should use profit/equity with an explicit "
      "negative-equity flag rather than the truncated `roe`.")
    # debt block bounds
    stres = p["debt_st"] - p[ST].sum(axis=1, min_count=3)
    P(f"\nBank/fin/AP split: no identity recovers it. When the ST block is fully missing ({st_m.sum():,} rows) only the total `debt_st` is known. "
      f"Where the block is present, bank+fin+AP short-term covers a median {(p[ST].sum(axis=1, min_count=3) / p['debt_st']).median():.1%} of debt_st "
      f"(residual >= 0 on {(stres[stres.notna()] >= -2).mean():.1%} of rows), so `debt_st` is a valid upper bound for each component.")
    P(f"\n`eqty_corp_family_tot`: 100% missing; drop. `days_rec`: {p['days_rec'].isna().mean():.1%} missing and inconsistent with AR/revenue; "
      "replace with a recomputed 365 x AR / revenue.")

    # ---- 6 candidate treatments
    P("\n## 6. Candidate treatment per field (evidence for feature-architect; the choice is theirs)\n")
    P("Ranked options: (a) reconstruct from an identity; (b) missing indicator + training-window median within sector; (c) native NaN handling "
      "by trees. All fits inside the training fold.\n")
    tr = []
    for c in t.index:
        nmiss = int(t.loc[c, "n_missing"])
        if c == "eqty_corp_family_tot":
            opt = "drop (100% missing)"
        elif c in ("roe",):
            opt = "(a) recompute profit/eqty_tot + negative-equity flag; never median-impute (missing = extreme/negative equity)"
        elif c == "days_rec":
            opt = "(a) recompute 365*AR/rev_operating; drop the provided field"
        elif c in RR.index and RR.loc[c, "share_recovered"] > 0.9 and RR.loc[c, "accuracy_on_present_rows"] > 0.99:
            opt = f"(a) reconstruct ({RR.loc[c, 'share_recovered']:.0%} recoverable, identity exact on {RR.loc[c, 'accuracy_on_present_rows']:.1%})"
        elif c in ST + LT:
            opt = "(b) block-missing indicator (one flag per block) + within-sector median of the component SHARE of debt_st/debt_lt; or (c)"
        elif c in RR.index and RR.loc[c, "share_recovered"] > 0:
            opt = f"(a) reconstruct where inputs present ({RR.loc[c, 'share_recovered']:.0%} recoverable, exact on {RR.loc[c, 'accuracy_on_present_rows']:.1%}) else (b)"
        elif c == "HQ_city":
            opt = "category 'missing' (unseen-category fallback)"
        else:
            opt = "(b) or (c); missing is rare"
        tr.append({"field": c, "n_missing": nmiss, "share": t.loc[c, "all_years"],
                   "rate_ratio_missing_vs_present": I.loc[c, "ratio"] if c in I.index else np.nan, "candidate": opt})
    TR = pd.DataFrame(tr).set_index("field")
    TR.to_csv(REP / "miss_treatment_candidates.csv")
    P(md(TR, ".4f"))
    (REP / "02_missingness.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
