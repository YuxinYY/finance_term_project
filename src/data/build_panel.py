"""Build labels (D-002, D-009), the cleaned panel and the frozen walk-forward splits.

Run:  python -m src.data.build_panel        (from the repo root)
Writes:
    data/interim/panel.parquet
    data/splits/walkforward.json, data/splits/walkforward_test_rows.parquet  (only if absent)
    reports/data/00_labels.md + reports/data/labels_*.csv
Shared label code (src/common/labels.py) is called with arguments, not edited.
"""
from __future__ import annotations

import json
import os
import stat
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from src.common.labels import make_labels  # noqa: E402
from src.data.codes import REGION_MACRO, ateco_section, province_region  # noqa: E402
from src.data.mdutil import md  # noqa: E402
from src.data.load_raw import read_raw  # noqa: E402

RAW = ROOT / "data/raw/train-2025.csv"
PANEL = ROOT / "data/interim/panel.parquet"
SPLITS = ROOT / "data/splits"
REP = ROOT / "reports/data"

PRIMARY_START = 6          # D-002 (assumption pending Roger/TA)
HORIZON = 12
STARTS = (0, 3, 6)
SENS_END = "2012-12-31"    # Appendix B statement


def label_one(df: pd.DataFrame, start: int, data_end: str, drop_after: str | None) -> pd.DataFrame:
    """make_labels + two auditor rules applied on top (proposed for src/common, OPEN):
    (1) a row whose window is not fully observed is 'censored' even if a default is observed
        inside it (make_labels marks those 'ok' with y=1, which gives censored years a 100%
        default rate and biases any fit that uses them);
    (2) rows dated on/after the firm's default are 'after_default' (none exist; checked).
    drop_after: def_dates after this date are treated as not observed (D-009 sensitivity)."""
    d = df[["id", "fs_year", "stmt_date", "def_date"]].copy()
    if drop_after is not None:
        d.loc[d["def_date"] > pd.Timestamp(drop_after), "def_date"] = pd.NaT
    lab = make_labels(d, start_months=start, horizon_months=HORIZON, data_end=data_end)
    complete = lab["win_end"] <= pd.Timestamp(data_end) + pd.Timedelta(days=1)
    after = lab["def_date"].notna() & (lab["def_date"] <= lab["stmt_dt"])
    status = lab["label_status"].astype(object).copy()
    status[(status == "ok") & ~complete] = "censored"
    status[after] = "after_default"
    y = lab["y"].where(status == "ok")
    return pd.DataFrame({"y": y, "status": status, "win_start": lab["win_start"],
                         "win_end": lab["win_end"], "complete": complete,
                         "censored_default_observed": (~complete) & (lab["y"] == 1)})




def main() -> None:
    df, na_report = read_raw(str(RAW))
    n = len(df)
    lines: list[str] = []
    P = lines.append
    P("# Labels: D-009 (2013 default dates) and D-002 (window choice)\n")
    P("Generated by `src/data/build_panel.py` (data-auditor, 2026-10-30). Every number below is computed by that script.\n")

    # ---------------- D-009 -----------------
    P("## 1. D-009: how `def_date` behaves\n")
    stmt_ok = (df["stmt_date"].dt.year == df["fs_year"]).all() and (df["stmt_date"].dt.strftime("%m-%d") == "12-31").all()
    P(f"- Rows: {n:,}. `stmt_date` == 31 Dec of `fs_year` on every row: **{stmt_ok}** (so the statement date is known, not assumed).")
    per_firm_nuniq = df.groupby("id")["def_date"].nunique()
    mixed = df.groupby("id")["def_date"].agg(lambda s: s.notna().any() and s.isna().any())
    P(f"- Firms with >1 distinct def_date: {int((per_firm_nuniq > 1).sum())}; firms with def_date on some rows but blank on others: {int(mixed.sum())}. "
      "=> `def_date` is a **firm-level** attribute repeated on every row of the firm.")
    firm = df.groupby("id").agg(def_date=("def_date", "first"), fy_min=("fs_year", "min"), fy_max=("fs_year", "max"), n=("fs_year", "size"))
    nf, nd = len(firm), int(firm["def_date"].notna().sum())
    P(f"- Firms: {nf:,}; firms with a default date: {nd:,} ({nd/nf:.2%}). Rows carrying a def_date: {int(df['def_date'].notna().sum()):,}.")
    P(f"- def_date range: {df['def_date'].min().date()} to **{df['def_date'].max().date()}**.")
    t = pd.DataFrame({"firms_defaulting": firm["def_date"].dt.year.value_counts().sort_index().astype(int),
                      "rows_carrying_date": df["def_date"].dt.year.value_counts().sort_index().astype(int)})
    t.index = t.index.astype(int)
    t.index.name = "def_year"
    P("\nDefaulting firms and rows by default year:\n")
    P(md(t, ".0f"))
    t.to_csv(REP / "labels_def_by_year.csv")
    mon = firm.loc[firm["def_date"] >= "2012-01-01", "def_date"].dt.to_period("M").value_counts().sort_index()
    mt = mon.rename("firms_defaulting").to_frame()
    mt.index = mt.index.astype(str)
    P("\nMonthly defaulting firms, 2012-01 to the last date (is 2013 thinner, i.e. partially observed?):\n")
    P(md(mt, ".0f"))
    m12 = mon[(mon.index >= pd.Period("2012-01", "M")) & (mon.index <= pd.Period("2012-05", "M"))].mean()
    m13 = mon[mon.index >= pd.Period("2013-01", "M")].mean()
    P(f"\nMean firms/month Jan-May 2012 = {m12:.1f}; Jan-May 2013 = {m13:.1f}. The 2013 dates run at a similar monthly "
      "intensity and stop abruptly after May 2013, which is consistent with default tracking that continued to 2013-05-31 "
      "rather than with stray errors. Appendix B's sentence ('no information ... after 12/31/2012') is contradicted by the file.")
    dd = df[df["def_date"].notna()].copy()
    dd["months"] = (dd["def_date"].dt.year - dd["stmt_date"].dt.year) * 12 + (dd["def_date"].dt.month - dd["stmt_date"].dt.month)
    bins = pd.cut(dd["months"], [0, 3, 6, 9, 12, 18, 24, 36, 120], right=True)
    P(f"\nRows dated on/after the firm's default (statement date >= def_date): **{int((dd['def_date'] <= dd['stmt_date']).sum())}**. "
      "So there are no post-default firm-years to drop; the exclusion rule is implemented anyway for the holdout-style data.")
    P(f"\nMonths from statement date to def_date, rows of defaulting firms (min {int(dd['months'].min())}, median {dd['months'].median():.0f}, max {int(dd['months'].max())}):\n")
    P(md(bins.value_counts().sort_index().rename("rows").to_frame(), ".0f"))
    firm_d = firm[firm["def_date"].notna()].copy()
    firm_d["gap_last_stmt_months"] = (firm_d["def_date"].dt.year - firm_d["fy_max"]) * 12 + firm_d["def_date"].dt.month - 12
    P("\nMonths from a defaulting firm's LAST statement to its default (firm level):\n")
    P(md(pd.cut(firm_d["gap_last_stmt_months"], [0, 3, 6, 12, 18, 24, 36, 120]).value_counts().sort_index().rename("firms").to_frame(), ".0f"))
    ct = pd.crosstab(firm_d["def_date"].dt.year, firm_d["fy_max"])
    P("\nDefault year (rows) x last fs_year in the panel (columns). No firm has a statement for its default year:\n")
    P(md(ct, ".0f"))
    # availability evidence: share of defaulters with a statement for the year before default, by default month
    have = set(zip(df["id"].tolist(), df["fs_year"].astype(int).tolist()))
    firm_d["has_prev_year_stmt"] = [(i, y - 1) in have for i, y in zip(firm_d.index, firm_d["def_date"].dt.year)]
    av = firm_d.groupby(firm_d["def_date"].dt.month)["has_prev_year_stmt"].agg(["mean", "size"])
    av.index.name = "default_month"
    P("\nShare of defaulting firms that HAVE a statement for the fiscal year just before the default year, by default month:\n")
    P(md(av.T, ".3f"))
    P(f"\nRises from {av['mean'].iloc[0]:.1%} (January defaults) to {av['mean'].iloc[-1]:.1%} (December defaults). Hypothesis: firms "
      "that default early in year Y often never file (or the provider never captured) the Y-1 statement. Consequence: a statement's presence "
      "in the file does not prove it was available before the default, but the file does contain Y-1 statements for many firms that "
      "defaulted in the first months of Y (statements a bank could probably not yet have seen: accounts are approved within 120 days of year-end, 180 if the statute allows, "
      "and filed within 30 days of approval; R-28, R-29, VERIFIED current text, 2007-2012 wording SECONDARY).")
    firm_d.reset_index().to_csv(REP / "labels_defaulting_firms.csv", index=False)

    data_end_primary = str(df["def_date"].max().date())
    P(f"\n**D-009 treatments.** PRIMARY: dates as given, `data_end` = last observed def_date = **{data_end_primary}**. "
      f"SENSITIVITY: def_dates after {SENS_END} set to missing and `data_end` = {SENS_END} (Appendix B literal reading).\n")

    # ---------------- D-002 -----------------
    P("## 2. D-002: label windows (12-month horizon) x D-009 treatment\n")
    P("Rule: y=1 if win_start <= def_date < win_end, win_start = stmt_date + start months, win_end = win_start + 12 months "
      "(`make_labels`). Exclusions: `already_defaulted` (default before window start: not a performing applicant), `after_default` "
      "(statement on/after default; 0 rows), `censored` (window ends after data_end). **Auditor change on top of make_labels**: a row whose "
      "window is incomplete is `censored` even when a default is observed inside it (make_labels keeps those as ok/y=1, which would put "
      "only defaults into the incomplete year; see 'censored_default_observed').\n")
    configs = {}
    summ, peryear = [], []
    for trt, end, drop in [("primary", data_end_primary, None), ("d2012", SENS_END, SENS_END)]:
        for s in STARTS:
            L = label_one(df, s, end, drop)
            configs[(trt, s)] = L
            ok = L["status"] == "ok"
            summ.append({"treatment": trt, "data_end": end, "start_months": s, "usable_rows": int(ok.sum()),
                         "defaults": int(L.loc[ok, "y"].sum()), "default_rate": L.loc[ok, "y"].mean(),
                         "already_defaulted": int((L["status"] == "already_defaulted").sum()),
                         "after_default": int((L["status"] == "after_default").sum()),
                         "censored": int((L["status"] == "censored").sum()),
                         "censored_default_observed": int(L["censored_default_observed"].sum()),
                         "defaulting_firms_with_a_y1_row": int(df.loc[L["y"] == 1, "id"].nunique()),
                         "complete_fs_years": ",".join(str(y) for y in sorted(df.loc[L["complete"], "fs_year"].unique()))})
            g = pd.DataFrame({"fs_year": df["fs_year"], "y": L["y"], "status": L["status"]})
            py = g.groupby("fs_year").agg(rows=("y", "size"), usable=("y", lambda v: v.notna().sum()), defaults=("y", "sum"),
                                         default_rate=("y", "mean"),
                                         already_defaulted=("status", lambda v: (v == "already_defaulted").sum()),
                                         censored=("status", lambda v: (v == "censored").sum()))
            for c in ["rows", "usable", "defaults", "already_defaulted", "censored"]:
                py[c] = py[c].astype(int)
            py.insert(0, "start_months", s)
            py.insert(0, "treatment", trt)
            peryear.append(py.reset_index())
    S = pd.DataFrame(summ)
    PY = pd.concat(peryear, ignore_index=True)
    S.to_csv(REP / "labels_sensitivity_summary.csv", index=False)
    PY.to_csv(REP / "labels_sensitivity_by_year.csv", index=False)
    P(f"Total defaulting firms in the file: {nd:,}.\n")
    P(md(S.set_index(["treatment", "start_months"])))
    P("\nPer fs_year (default_rate over usable rows):\n")
    P(md(PY.set_index(["treatment", "start_months", "fs_year"])))
    # which fs_years differ between treatments
    diffs = []
    for s in STARTS:
        a, b = configs[("primary", s)], configs[("d2012", s)]
        for yr in sorted(df["fs_year"].unique()):
            m = df["fs_year"] == yr
            if not (a.loc[m, "status"].equals(b.loc[m, "status"]) and a.loc[m, "y"].fillna(-1).equals(b.loc[m, "y"].fillna(-1))):
                diffs.append(f"start={s}: fs_year {yr}")
    P("\nfs_years whose labels differ between PRIMARY and the 2012 SENSITIVITY: " + ("; ".join(diffs) if diffs else "none") + ".")
    P("All other fs_years are identical under both treatments, so D-009 does not move any walk-forward fold under the primary window.")

    # ---------------- Panel -----------------
    pan = df.copy()
    pan.insert(0, "row_id", (pan["id"].astype("int64") * 10000 + pan["fs_year"].astype("int64")).astype("int64"))
    assert pan["row_id"].is_unique
    pan["region"] = pan["HQ_city"].map(lambda c: province_region(c) if pd.notna(c) else None)
    pan["macro_area"] = pan["region"].map(REGION_MACRO)
    pan["ateco_section"] = pan["ateco_sector"].map(lambda c: ateco_section(c) if pd.notna(c) else None)
    for c in ["HQ_city", "legal_struct", "ateco_sector", "region", "macro_area", "ateco_section"]:
        pan[c] = pan[c].astype("string")
    Lp = configs[("primary", PRIMARY_START)]
    pan["y"] = Lp["y"]
    pan["label_status"] = Lp["status"].astype("string")
    pan["win_start"], pan["win_end"] = Lp["win_start"], Lp["win_end"]
    for (trt, s), L in configs.items():
        suf = f"s{s}" + ("" if trt == "primary" else "_d2012")
        pan[f"y_{suf}"] = L["y"]
        pan[f"status_{suf}"] = L["status"].astype("string")
    PANEL.parent.mkdir(parents=True, exist_ok=True)
    pan.to_parquet(PANEL, index=False)
    P(f"\n## 3. Panel written\n\n`data/interim/panel.parquet`: {len(pan):,} rows x {pan.shape[1]} columns. Primary label `y`/`label_status` = "
      f"start {PRIMARY_START} months, 12-month horizon, data_end {data_end_primary}. Status counts: "
      + ", ".join(f"{k}={v:,}" for k, v in pan["label_status"].value_counts().items()) + ".")

    # ---------------- Splits -----------------
    wf = SPLITS / "walkforward.json"
    complete_years = sorted(int(y) for y in pan.loc[Lp["complete"], "fs_year"].unique())
    years = sorted(int(y) for y in pan["fs_year"].unique())
    folds, rows = [], []
    for k, ty in enumerate([y for y in complete_years if y > years[0]], start=1):
        tr_years = [y for y in years if y < ty]
        tr = pan[pan["fs_year"].isin(tr_years) & (pan["label_status"] == "ok")]
        te = pan[(pan["fs_year"] == ty) & (pan["label_status"] == "ok")]
        seen_ids = set(pan.loc[pan["fs_year"].isin(tr_years), "id"].tolist())
        seen = te["id"].isin(seen_ids)
        folds.append({"fold": k, "train_years": tr_years, "test_year": ty,
                      "n_train": int(len(tr)), "train_defaults": int(tr["y"].sum()), "train_default_rate": round(float(tr["y"].mean()), 6),
                      "n_test": int(len(te)), "test_defaults": int(te["y"].sum()), "test_default_rate": round(float(te["y"].mean()), 6),
                      "n_test_seen_firm": int(seen.sum()), "n_test_new_firm": int((~seen).sum()),
                      "test_defaults_seen_firm": int(te.loc[seen, "y"].sum()), "test_defaults_new_firm": int(te.loc[~seen, "y"].sum())})
        rows.append(pd.DataFrame({"row_id": te["row_id"].values, "fold": k, "test_year": ty, "firm_seen_in_train": seen.values}))
    # sensitivity fold (only valid for start 0/3 labels under the primary D-009 treatment)
    sens_folds = []
    for s in (0, 3):
        L = configs[("primary", s)]
        cy = sorted(int(y) for y in pan.loc[L["complete"], "fs_year"].unique())
        extra = [y for y in cy if y not in complete_years and y > years[0]]
        for ty in extra:
            tr_years = [y for y in years if y < ty]
            ok = L["status"] == "ok"
            te = pan[(pan["fs_year"] == ty) & ok]
            seen = te["id"].isin(set(pan.loc[pan["fs_year"].isin(tr_years), "id"]))
            sens_folds.append({"fold": f"S{s}-{ty}", "label_column": f"y_s{s}", "status_column": f"status_s{s}",
                               "train_years": tr_years, "test_year": ty,
                               "n_train": int((pan["fs_year"].isin(tr_years) & ok).sum()),
                               "train_defaults": int(L.loc[pan["fs_year"].isin(tr_years) & ok, "y"].sum()),
                               "n_test": int(len(te)), "test_defaults": int(L.loc[te.index, "y"].sum()),
                               "n_test_seen_firm": int(seen.sum()), "n_test_new_firm": int((~seen).sum())})
    spec = {
        "version": 1, "created": "2026-10-30", "created_by": "data-auditor (src/data/build_panel.py)",
        "panel": "data/interim/panel.parquet", "row_id": "id * 10000 + fs_year (int64; unique; reproducible from any file with id and fs_year)",
        "label": {"column": "y", "status_column": "label_status", "start_months": PRIMARY_START, "horizon_months": HORIZON,
                  "data_end": data_end_primary, "d009_treatment": "primary (def_date as given)"},
        "design": "expanding window, out-of-time: train on fs_year < test_year (i.e. <= t), test on fs_year == test_year (t+1); "
                  "only test years whose label windows are fully observed under the primary label",
        "train_rows": "panel rows with fs_year in train_years AND label_status == 'ok'",
        "test_rows": "panel rows with fs_year == test_year AND label_status == 'ok' (listed in walkforward_test_rows.parquet)",
        "firm_seen_in_train": "True if the firm id has at least one panel row (any label_status) with fs_year in train_years",
        "folds": folds,
        "sensitivity_folds_not_primary": sens_folds,
        "excluded_test_years": {str(y): "label window not fully observed under primary label" for y in years if y not in complete_years},
    }
    if wf.exists():
        P("\n`data/splits/walkforward.json` already exists: NOT overwritten (frozen).")
    else:
        SPLITS.mkdir(parents=True, exist_ok=True)
        tr_path = SPLITS / "walkforward_test_rows.parquet"
        pd.concat(rows, ignore_index=True).to_parquet(tr_path, index=False)
        wf.write_text(json.dumps(spec, indent=2))
        for p in (wf, tr_path):
            os.chmod(p, stat.S_IRUSR | stat.S_IRGRP | stat.S_IROTH)
    FT = pd.DataFrame(folds).drop(columns=["train_years"]).assign(train_years=[f"{f['train_years'][0]}-{f['train_years'][-1]}" for f in folds])
    P("\n## 4. Walk-forward folds (primary label)\n")
    P(md(FT.set_index("fold"), ".4f"))
    if sens_folds:
        P("\nSensitivity-only folds (not primary):\n")
        P(md(pd.DataFrame(sens_folds).drop(columns=["train_years"]).set_index("fold"), ".4f"))
    FT.to_csv(REP / "walkforward_folds.csv", index=False)

    # ---------------- Recommendation -----------------
    P("\n## 5. Recommendation (assumption pending Roger/TA; DECISION_LOG D-002)\n")
    s0, s6 = configs[("primary", 0)], configs[("primary", 6)]
    same = df["fs_year"].between(2007, 2010)
    r0 = s0.loc[same & (s0["status"] == "ok"), "y"].mean()
    r6 = s6.loc[same & (s6["status"] == "ok"), "y"].mean()
    P(f"- **Primary: start = {PRIMARY_START} months, 12-month horizon.** Business reason: for a 31-Dec year-end, accounts are approved "
      "within 120 days (180 if the statute allows) and filed within 30 days of approval (R-28, R-29), i.e. public by about end-May, or "
      "end-July if extended. A lending decision based on the FY t statement therefore happens from roughly mid-year t+1, and the PD the "
      "bank needs covers the 12 months after that. We do not know actual filing dates; this is an assumption.")
    P(f"- Data evidence: {int((s6['status'] == 'already_defaulted').sum()):,} rows pair a statement with a default 0-6 months after "
      "fiscal year-end, before the statement would normally be public; start = 0 would train on these as defaults although a bank "
      "could not have scored them with that statement. The share of defaulters that still have the prior-year statement rises with the "
      "default month (section 1), so these statements' presence does not show they were available in time.")
    P(f"- Level consequence (same fs_years 2007-2010): default rate {r6:.4f} at start 6 vs {r0:.4f} at start 0 "
      f"(ratio {r6 / r0:.2f}). The window choice moves the calibration level by about a third: this is why the holdout's window is an OPEN "
      "question for Roger/TA.")
    obs11 = s6.loc[(df["fs_year"] == 2011) & s6["censored_default_observed"]].shape[0]
    n11 = int(((df["fs_year"] == 2011) & (s6["status"] != "already_defaulted")).sum())
    P(f"- Cost: fs_year 2011 is censored at start 6 (window 2012-06-30 to 2013-06-30, data end 2013-05-31: one month short), so only 3 "
      "folds (test 2008-2010) and the final model cannot use 2011 statements as labelled data. Under start 0, 2011 is fully observed (4 folds). "
      "Fold S0-2011 in walkforward.json keeps that comparison possible.")
    P("\n**Censoring treatments** (for any row whose window is not fully observed):\n")
    P(f"- *Drop* (ADOPTED for evaluation): unbiased for the years kept; loses the newest vintage. fs_year 2011 under start 6: "
      f"{n11:,} performing rows dropped, {obs11:,} of them with a default observed in the first 11 months.")
    P(f"- *Keep as 0*: biases the rate down. fs_year 2011 at start 6 would get {obs11 / n11:.4f} from 11 of 12 months "
      f"(x12/11 = {obs11 / n11 * 12 / 11:.4f} if June 2013 looked like the average month); fs_year 2012 at start 0 would get "
      f"{int(configs[('primary', 0)]['censored_default_observed'].sum()):,} defaults from 5 of 12 months "
      f"({configs[('primary', 0)]['censored_default_observed'].sum() / (df['fs_year'] == 2012).sum():.4f}), far below the 2007-2011 rates.")
    P("- *Keep with y=1 only where observed* (what `make_labels` does by default): only defaults enter the incomplete year, a 100% "
      "default rate for that year; never use.")
    P("- OPEN option for the final fit only: include fs_year 2011 at start 6 with 11/12 months observed (a small, quantified downward "
      "bias, above). Not used in any fold.")
    P("\n**Firm-years after a firm's default**: dropped by rule (`after_default`); the training file has none (0 rows). Rows of a firm "
      "after its default would describe a firm that is no longer a performing applicant.")
    (REP / "00_labels.md").write_text("\n".join(lines) + "\n")
    (REP / "na_report_train.json").write_text(json.dumps(na_report, indent=2, default=str))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
