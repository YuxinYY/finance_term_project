"""Build experiments/gbm/comparison_r2b.md from the CSV/JSON files written by run_round2b.py and explain_r2b.py.
Every number in the markdown is read from those files (no hand-typed metrics)."""
from __future__ import annotations

import json
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))


def md(df, fmt=".5g"):
    return df.to_markdown(index=False, floatfmt=fmt)


def gb25_section():
    """GB-25 = GB-20 with interest_to_sales constrained +. Files written by run_round2b.py and gb25_check.py."""
    d = os.path.join(HERE, "GB-25")
    if not os.path.exists(os.path.join(d, "gb25_bootstrap_1000.csv")):
        return []
    r = lambda f: pd.read_csv(os.path.join(d, f))
    m = r("gb25_metrics.csv")
    m = m[m.model.isin(["GB-01", "GB-20", "GB-25"]) & m.subset.isin(["ALL", "2008", "2009", "2010"])]
    mono = r("gb25_monotone.csv")
    return ["## 8. GB-25: GB-20 with interest_to_sales constrained + (pre-specified fix of D-125; decision D-130)\n",
            "Only permitted question: what does the restored sign cost? Same recipe as GB-20, so the grid is re-chosen on slice A "
            "(fold 2 moves to min_data_in_leaf 2000). Outer folds scored once. Bootstrap 1,000 draws, firm-clustered, d = first minus second.\n",
            "### Metrics\n", md(m[["model", "subset", "auc", "log_loss", "cal_slope", "ratio_obs_to_pred"]]), "",
            "### Paired bootstrap\n", md(r("gb25_bootstrap_1000.csv"), ".5f"), "",
            f"### Monotone check, fold 3\n\nConstrained: {len(mono)}; features violating: "
            f"{int(((mono.pd_violation_share > 1e-9) | (mono.ice_rows_violating > 0)).sum())}; ICE rows violating: "
            f"{int(mono.ice_rows_violating.sum())}; with 0 splits: {list(mono[mono.n_splits == 0].feature)}.\n",
            md(mono[mono.feature == "interest_to_sales"]), "",
            "### Same-year in-sample vs OOT AUC\n", md(r("gb25_same_year_gap.csv"), ".4f"), "",
            "### interest_to_sales and interest_to_assets by decile, same 20,000 rows and bins for both models\n", md(r("gb25_shap_deciles.csv"), ".4f"), "",
            "### Interest family and asset_turnover: importance and partial-dependence range\n", md(r("gb25_interest_family.csv"), ".4f"), "",
            "### Where the top-decile effect went: largest SHAP changes in interest_to_sales D9 and D10\n", md(r("gb25_top_decile_moves.csv"), ".4f"), "",
            "### Code-mapping check\n", "Provinces vs R-53's file (region of all 110 codes): `GB-25/mapping_check_provinces_r53.csv`. "
            "Divisions used in the write-up vs R-54 pp. 51-53: `GB-25/mapping_check_divisions_r54.csv`.\n"]


def headline():
    """Short read-first tables, all read from the same CSVs as the detailed sections below."""
    m = pd.read_csv(os.path.join(HERE, "comparison_r2b_metrics.csv"))
    rows = []
    for e in ("GB-01", "GB-09", "GB-20", "GB-23", "CAL-01", "GB-20+CAL", "GB-23+CAL"):
        d = m[m.model == e].set_index("subset")
        rows.append({"model": e, **{f"AUC {s_}": d.loc[s_, "auc"] for s_ in ("ALL", "2008", "2009", "2010")},
                     **{f"LL {s_}": d.loc[s_, "log_loss"] for s_ in ("ALL", "2010")},
                     **{f"slope {s_}": d.loc[s_, "cal_slope"] for s_ in ("ALL", "2008", "2009", "2010")},
                     "obs/pred ALL": d.loc["ALL", "ratio_obs_to_pred"], "obs/pred 2010": d.loc["2010", "ratio_obs_to_pred"]})
    b = pd.read_csv(os.path.join(HERE, "comparison_r2b_bootstrap_1000.csv"))
    b = b[b.new == "GB-20"].drop(columns=["new", "old"])
    ov = pd.read_csv(os.path.join(HERE, "comparison_r2b_overfit.csv"))
    ov = ov[ov.view.isin(["referee r1b (calibration cache)", "pd_oof_enc"])]
    return ["## 0. Read first\n", "### Metrics\n", md(pd.DataFrame(rows), ".4f"), "",
            "### GB-20 minus GB-01, firm-clustered bootstrap, 1,000 draws\n", md(b, ".5f"), "",
            "### Same-year in-sample vs OOT AUC\n", md(ov[["model", "year", "in_sample_fold", "auc_in_sample", "auc_oot", "gap_auc"]], ".4f"), ""]


def main():
    out = ["# Round 2 phase B: GBM on feature set full2 (GB-20..GB-25)\n",
           "Generated by `experiments/gbm/report_r2b.py` from files written by `run_round2b.py` and "
           "`explain_r2b.py`. Outer folds = frozen walk-forward (test 2008/09/10), each final configuration "
           "scored once. Bootstrap: referee's firm-clustered paired bootstrap (score_r1.py `bootstrap_draws`/"
           "`ci`/`pair_row`, exec'd without running the script body), 200 draws, seed 0; d = first model "
           "minus second. LOCKBOX: fs_year >= 2011 never read. D-062: full2 was designed on 2007-09, so the "
           "2010 column is the clean test.\n"]
    out += headline()
    met = pd.read_csv(os.path.join(HERE, "comparison_r2b_metrics.csv"))
    piv = met.pivot_table(index="model", columns="subset", values="auc")
    ll = met.pivot_table(index="model", columns="subset", values="log_loss")
    sl = met.pivot_table(index="model", columns="subset", values="cal_slope")
    cols = ["ALL", "2008", "2009", "2010", "seen", "new"]
    t = pd.concat({"AUC": piv[cols], "log loss": ll[cols], "cal slope": sl[cols]}, axis=1)
    t.columns = [f"{a} {b}" for a, b in t.columns]
    out += ["## 1. Metrics (src/common/metrics.py)\n",
            "`+CAL` = common calibration (CAL-01 method: prior shift to rule e, floor 0.03%, cap 99%; reproduces "
            "CAL-01 from GB-01 exactly). Own-calibration rows are each model's submitted `pd`.\n",
            md(t.reset_index()), ""]
    lvl = met[met.subset.isin(["ALL", "2010"])][["model", "subset", "mean_pd", "observed_dr", "ratio_obs_to_pred",
                                                  "brier", "cal_intercept", "cal_slope"]]
    out += ["### Level (calibration-in-the-large)\n", md(lvl), ""]
    bs = pd.read_csv(os.path.join(HERE, "comparison_r2b_bootstrap.csv"))
    keep = ["new", "old", "subset", "d_auc", "d_auc_lo", "d_auc_hi", "d_log_loss", "d_log_loss_lo", "d_log_loss_hi",
            "d_auc_share_fav_new", "n_draws"]
    out += ["## 2. Paired firm-clustered bootstrap\n", md(bs[keep]), ""]
    win = []
    for (a, b), g in bs.groupby(["new", "old"], sort=False):
        g = g.set_index("subset")
        win.append({"new": a, "old": b,
                    "pooled AUC CI excludes 0 (better)": bool(g.loc["ALL", "d_auc_lo"] > 0),
                    "pooled LL CI excludes 0 (better)": bool(g.loc["ALL", "d_log_loss_hi"] < 0),
                    "AUC better in all 3 years": bool((g.loc[["2008", "2009", "2010"], "d_auc"] > 0).all()),
                    "LL better in all 3 years": bool((g.loc[["2008", "2009", "2010"], "d_log_loss"] < 0).all()),
                    "2010 AUC CI excludes 0": bool(g.loc["2010", "d_auc_lo"] > 0)})
    out += ["### Win rule (CI vs reference excludes 0 AND better in all 3 years)\n", md(pd.DataFrame(win)), ""]
    p = os.path.join(HERE, "comparison_r2b_bootstrap_1000.csv")
    if os.path.exists(p):
        out += ["### 1,000-draw bootstrap vs GB-01, year x seen/new cells, and the seen-minus-new gain gap (D-060)\n",
                md(pd.read_csv(p)), ""]
    p = os.path.join(HERE, "GB-21", "ablation_summary.csv")
    if os.path.exists(p):
        ab = pd.read_csv(p)
        out += ["## 3. GB-21 ablation by group (inner splits only; fixed GB-01 cfg per fold; 3 seeds; "
                "metrics on inner slice B, which was used neither for fitting nor early stopping)\n",
                "fold_inner 2 = train 2007, early stop on 2008 half A, evaluate 2008 half B. fold_inner 3 = train "
                "2007-08, early stop 2009 A, evaluate 2009 B. d = variant minus full2 (seed-averaged predictions), "
                "firm-clustered bootstrap 200 draws on B. Positive d_auc / negative d_ll = the group HURTS.\n",
                md(ab), ""]
    p = os.path.join(HERE, "GB-24", "extras_summary.csv")
    if os.path.exists(p):
        out += ["## 3b. GB-24 inner-only extras (same slices, cfg and seeds as GB-21; outer folds NOT scored)\n",
                "Single-feature drops, unconstrained twins (does full2 add information, or buy back the constraint cost?) "
                "and GB-08's relaxed constraints. d = a minus b on slice B, firm-clustered bootstrap, 200 draws.\n",
                md(pd.read_csv(p)), ""]
    p = os.path.join(HERE, "GB-24", "extras2_summary.csv")
    if os.path.exists(p):
        out += ["### GB-24 part 2: the unconstrained new features with the hardest shapes (inner only)\n", md(pd.read_csv(p)), ""]
    p = os.path.join(HERE, "GB-23", "inner_choice.csv")
    if os.path.exists(p):
        out += ["## 4. GB-23 inner choice, recorded BEFORE GB-23's outer folds: GB-09's cfg vs GB-20's grid choice on "
                "full2 (A = selection, B = untouched check). Gains are positive when GB-09's cfg is better; the v1 "
                "columns come from GB-09/selection_check.csv.\n", md(pd.read_csv(p).T.reset_index(), ".6g"), ""]
    p = os.path.join(HERE, "comparison_r2b_overfit.csv")
    if os.path.exists(p):
        out += ["## 5. Same-year in-sample vs out-of-time AUC (referee definition, r1b_addons.py)\n",
                "In-sample = year t scored by a fold whose training includes t; OOT = year t scored by the fold "
                "for which t is the test year (same rows). For full2: `pd_oof_enc` = training rows with out-of-fold "
                "encodings (what the booster was trained on); `pd_fulltable_enc` = full-window encodings (rows see "
                "their own label inside the encoding: upper bound).\n", md(pd.read_csv(p)), ""]
    for e in ("GB-20", "GB-01"):
        p = os.path.join(HERE, "GB-22", f"face_validity_{e}.csv")
        if os.path.exists(p):
            fv = pd.read_csv(p)
            out += [f"## 6. GB-22 face validity, {e} fold-3 model (2010 sample: SHAP 20,000 rows, partial dependence "
                    "3,000 rows, ICE 500 rows)\n",
                    f"Constrained features: {int(fv.constrained.sum())}; VIOLATIONS: {int((fv.verdict == 'VIOLATION').sum())}\n",
                    md(fv), ""]
            ice = pd.read_csv(os.path.join(HERE, "GB-22", f"ice_check_{e}.csv"))
            out += [f"### ICE check {e}: rows with any step against the sign\n",
                    f"max over features of max_step_against_sign: {ice.max_step_against_sign_logodds.max():.3g}; "
                    f"rows with any violation (sum over features): {int(ice.rows_with_any_violation.sum())}\n"]
    for f, title in (("shap_top15_GB-20.csv", "Top-15 mean |SHAP| (GB-20 fold 3)"),
                     ("shap_by_family_GB-20.csv", "Mean |SHAP| by family (GB-20)"),
                     ("shap_top15_GB-01.csv", "Top-15 mean |SHAP| (GB-01 fold 3, same rows)"),
                     ("dependence_bins.csv", "Dependence by decile: unconstrained new features + encodings"),
                     ("tfr_by_segment.csv", "tfr_ratio: what it separates (2010 sample)"),
                     ("tfr_train_tables.csv", "tfr_ratio bands by sector and equity tercile (training rows 2007-09)"),
                     ("tfr_shap_by_equity.csv", "tfr_ratio SHAP by TFR band x equity tercile (2010 sample, excl. L)"),
                     ("tfr_suppression_logit.csv", "tfr_ratio coefficient alone vs next to correlated ratios (training rows, excl. L)"),
                     ("tfr_by_turnover.csv", "Default rate by TFR band x asset-turnover tercile (training rows, excl. L)"),
                     ("tfr_shap_by_turnover.csv", "tfr_ratio SHAP by TFR band x turnover tercile (2010 sample, excl. L)"),
                     ("tfr_train_auc.csv", "tfr_ratio univariate AUC by subset (training rows 2007-09)"),
                     ("tfr_tenure_proxy.csv", "Fund stock / wage bill, a tenure proxy (D-010 hypothesis; non-L firms, training rows)"),
                     ("reason_code_stats.csv", "Reason codes: how often the top 3 repeat a family or use a new feature"),
                     ("tfr_interaction_proxy.csv", "tfr_ratio: features most correlated with its within-band SHAP residual"),
                     ("encoding_persistence.csv", "Encodings fitted on the past vs the next year's defaults (diagnostic, no choice uses it)"),
                     ("encoding_extremes_fold3.csv", "Lowest / highest encoded levels, fold-3 table vs 2010 default rate (levels with >= 200 rows)"),
                     ("reason_codes.csv", "Reason codes, 3 example 2010 firms (GB-20)")):
        p = os.path.join(HERE, "GB-22", f)
        if os.path.exists(p):
            out += [f"### {title}\n", md(pd.read_csv(p), ".4g"), ""]
    for e in ("GB-20", "GB-23"):
        p = os.path.join(HERE, e, "config.json")
        if os.path.exists(p):
            c = json.load(open(p))
            rows = [{"fold": f["fold"], "chosen_cfg": json.dumps(f["chosen_cfg"]), "best_iter": f["best_iter"],
                     "final_trees": f["n_final_trees"], "B_defaults": f["defaults_B_calibration"],
                     "isotonic_eligible": f["isotonic_eligible"], "B_raw": f["calibration_compare_B"]["raw"],
                     "B_platt": f["calibration_compare_B"]["platt"], "B_iso": f["calibration_compare_B"]["isotonic"],
                     "platt_b": f["platt_on_B"]["b"], "sec_per_100k": f["predict_secs_per_100k"]}
                    for f in c["folds"]]
            out += [f"## 7. {e} per-fold choices and calibration comparison on inner B\n", md(pd.DataFrame(rows)), ""]
    out += gb25_section()
    with open(os.path.join(HERE, "comparison_r2b.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
