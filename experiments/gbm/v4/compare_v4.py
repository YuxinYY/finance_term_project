"""LGB-v4-mono vs LGB-v4-free: per-test-year paired firm-clustered bootstrap (src/common/metrics.py)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import train_v4 as T  # noqa: E402
from src.common import metrics as M  # noqa: E402

OUT = T.OUT
N_BOOT = 1000


def main():
    a = pd.read_parquet(OUT / "LGB-v4-mono/oot_predictions.parquet")
    b = pd.read_parquet(OUT / "LGB-v4-free/oot_predictions.parquet")
    m = a.merge(b, on=["row_id", "round", "fs_year", "label"], suffixes=("_mono", "_free"))
    assert len(m) == len(a) == len(b)
    rows = []
    for yr, g in m.groupby("fs_year"):
        firm = g["row_id"] // 10000
        # pd_shift only: the shift is monotone within a year, so AUC is identical to pd_raw
        for pcol in ("pd_shift",):
            bs = M.paired_bootstrap(g["label"], g[f"{pcol}_free"], g[f"{pcol}_mono"], firm, n_boot=N_BOOT, seed=0)
            bs.insert(0, "pd", pcol)
            bs.insert(0, "test_year", yr)
            bs["auc_mono"] = M.auc(g["label"], g[f"{pcol}_mono"])
            bs["auc_free"] = M.auc(g["label"], g[f"{pcol}_free"])
            bs["ll_mono"] = M.log_loss(g["label"], g[f"{pcol}_mono"])
            bs["ll_free"] = M.log_loss(g["label"], g[f"{pcol}_free"])
            rows.append(bs)
    res = pd.concat(rows)
    res.to_csv(OUT / "comparison_bootstrap.csv", index=False)
    viol = {}
    for v in ("mono", "free"):
        fv = pd.read_csv(OUT / f"LGB-v4-{v}/face_validity.csv")
        viol[v] = {int(r): {"shap": int(g["shap_violation"].sum()), "ice": int(g["ice_violation"].sum()),
                            "shap_list": sorted(g.loc[g["shap_violation"], "feature"]),
                            "ice_list": sorted(g.loc[g["ice_violation"], "feature"])}
                   for r, g in fv.groupby("round")}
    (OUT / "comparison_violations.json").write_text(json.dumps(viol, indent=1))
    write_md(res, viol)
    print(res.to_string())
    print(json.dumps(viol, indent=1))


