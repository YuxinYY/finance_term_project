def write_md(res, viol):
    mt = {v: pd.read_csv(OUT / f"LGB-v4-{v}/metrics_test.csv") for v in ("mono", "free")}
    cfg = {v: json.loads((OUT / f"LGB-v4-{v}/config.json").read_text()) for v in ("mono", "free")}
    L = ["# LGB-v4-mono vs LGB-v4-free (v4 temporal_year split, test years FY2009 and FY2010)", "",
         "Generated by `experiments/gbm/v4/compare_v4.py`. Same 13-config search for both variants, chosen on "
         "validation years only. Bootstrap: `src/common/metrics.paired_bootstrap`, 1,000 draws, firms resampled "
         "(one row per firm per test year), seed 0. Positive dAUC favours free; negative dLL favours free. "
         "AUC is identical for pd_raw and pd_shift (the shift is monotone within a year).", "",
         "## Chosen configurations", ""]
    for v in ("mono", "free"):
        L.append(f"- LGB-v4-{v}: config {cfg[v]['chosen_config_id']} `{json.dumps(cfg[v]['chosen_params'])}`")
    L += ["", "## Test metrics", "",
          "| Variant | PD | Test year | AUC | AR | Brier | Log-loss | Obs/Pred |", "|---|---|---|---|---|---|---|---|"]
    for v in ("mono", "free"):
        for _, r in mt[v].iterrows():
            L.append(f"| {v} | {r['pd']} | {r['group']} | {r['auc']:.4f} | {r['ar']:.4f} | {r['brier']:.5f} | "
                     f"{r['log_loss']:.5f} | {r['ratio_obs_to_pred']:.3f} |")
    L += ["", "## Paired bootstrap, free minus mono (pd_shift)", "",
          "| Test year | Metric | Point | 95% CI | Share of draws favouring free |", "|---|---|---|---|---|"]
    for _, r in res.iterrows():
        L.append(f"| {r['test_year']} | {r['metric']} | {r['point']:+.5f} | [{r['ci_low']:+.5f}, {r['ci_high']:+.5f}] | "
                 f"{r['share_favouring_new']:.3f} |")
    L += ["", "## Face-validity violations (features with an expected sign; `face_validity.csv`)", "",
          "SHAP violation: Spearman(feature value, TreeSHAP) has |rho| >= 0.05 and the opposite sign to the "
          "expected one. ICE violation: for more than 10% of 500 test rows, moving the feature from its 5th to its "
          "95th test-year percentile (others fixed) changes the PD against the expected sign. face_validity.csv "
          "also has the strict share (any step against the sign on a 41-point grid).", "",
          "| Variant | Round (test year) | SHAP violations | ICE violations | SHAP-violating features | ICE-violating features |",
          "|---|---|---|---|---|---|"]
    for v in ("mono", "free"):
        for r, d in viol[v].items():
            L.append(f"| {v} | {r} (FY{2008 + int(r)}) | {d['shap']} | {d['ice']} | {', '.join(d['shap_list']) or '-'} | "
                     f"{', '.join(d['ice_list']) or '-'} |")
    L += ["", "## Earlier results on the same test years (NOT like-for-like)", "",
          "Model settings, splits and calibration differ: the reference rows are other people's runs with their own "
          "hyper-parameters; the v4 rows are this freshly tuned run. Only test AUC is compared.", "",
          "| Source | Constraint | FY2009 AUC | FY2010 AUC |", "|---|---|---|---|"]
    for src, kind, a9, a10 in REF:
        L.append(f"| {src} | {kind} | {a9:.4f} | {a10:.4f} |")
    for v in ("mono", "free"):
        a = mt[v][mt[v]["pd"] == "pd_raw"].set_index("group")["auc"]
        L.append(f"| experiments/gbm/v4/LGB-v4-{v}/metrics_test.csv (v4 temporal_year, 81 features, this run) | "
                 f"{'monotone' if v == 'mono' else 'free'} | {a[2009]:.4f} | {a[2010]:.4f} |")
    (OUT / "comparison_tables.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
