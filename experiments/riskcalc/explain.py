"""Explainability pack for the best RiskCalc model (RC-03), fold 3 (trained on fs_year 2007-2009).

    python experiments/riskcalc/explain.py  -> experiments/riskcalc/RC-03/{explain.md, *.png, *.csv}

Uses only the frozen params files (no refitting). Training rows are read only to describe the
distribution of the drivers (medians, importance); test rows (2010) only to pick example firms.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy.stats import norm  # noqa: E402

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))
import riskcalc as RC  # noqa: E402
from src.features import build as B  # noqa: E402

EXP = "RC-03"
OD = HERE / EXP

LABEL = {  # plain-language names for credit officers
    "log_assets": "Total assets (size)",
    "equity_ratio": "Book equity / total assets",
    "st_debt_ratio": "Short-term liabilities / total assets",
    "cash_ratio": "Cash / total assets",
    "roa_net": "Net profit / total assets (ROA)",
    "interest_coverage": "EBITDA / interest expense",
    "interest_to_assets": "Interest expense / total assets",
    "ar_days": "Receivable days (AR / sales x 365)",
    "tangible_ratio": "Tangible fixed assets / total assets",
    "ap_days": "Payable days (trade payables / COGS x 365)",
    "bank_debt_ratio": "Bank debt / total assets",
    "neg_equity": "Negative equity flag",
}
SLOG = {c for c in B.NUM_FEATURES if B.META[c].get("slog")}


def natural(c, v):
    """Feature value -> natural units for display."""
    v = np.asarray(v, float)
    if c in SLOG:
        return np.sign(v) * np.expm1(np.abs(v))
    if c == "log_assets":
        return np.exp(v) / 1e6
    return v


def fmt(c, v):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "missing"
    x = float(natural(c, v))
    if c == "log_assets":
        return f"EUR {x:,.1f}MM"
    if c in ("ar_days", "ap_days"):
        return f"{x:,.0f} days"
    if c == "interest_coverage":
        return f"{x:,.1f}x"
    return f"{100 * x:.1f}%"


def main():
    P = {k: RC.load_params(OD / f"params_fold{k}.json") for k in (1, 2, 3)}
    p3 = P[3]
    ratios = [c[2:] for c in p3["design_columns"] if c.startswith("T_")]
    signs = B.expected_signs()
    panel = pd.read_parquet(ROOT / "data/interim/panel.parquet",
                            filters=[("fs_year", "in", [2007, 2008, 2009, 2010])])
    tr = panel[(panel.fs_year <= 2009) & (panel.label_status == "ok")].reset_index(drop=True)
    tests = pd.read_parquet(ROOT / "data/splits/walkforward_test_rows.parquet")
    te = panel.set_index("row_id").loc[tests.loc[tests.fold == 3, "row_id"]].reset_index()
    md = [f"# {EXP} explainability pack (fold 3 model: trained on fs_year 2007-2009)", "",
          "Generated by `experiments/riskcalc/explain.py` from the frozen params files "
          f"`{EXP}/params_fold{{1,2,3}}.json` (no refitting). Architecture (R-01 Sec. 3.1 p. 14): "
          "PD = F(Phi(sum_i beta_i T_i(x_i) + sum_j gamma_j I_j)). Each T_i is the ratio's "
          "training-window default rate by quantile bin (shrunk to the base rate, made monotone in the "
          "expected direction); it enters the probit as Phi^-1(T_i).", ""]

    # ---------------- 1. driver curves T_i -------------------------------------------------
    Xtr = B.transform(tr, p3["features"])
    Ztr, s_tr = RC.index_riskcalc(tr, p3, X=Xtr)
    n = len(ratios)
    fig, axes = plt.subplots(int(np.ceil(n / 4)), 4, figsize=(18, 4 * int(np.ceil(n / 4))))
    rows = []
    for ax, c in zip(axes.ravel(), ratios):
        for k, ls, col in ((1, ":", "0.6"), (2, "--", "0.4"), (3, "-", "C3")):
            t = P[k]["transforms"][c]
            kx = natural(c, t["knots_x"])
            ax.plot(kx, 100 * np.array(t["rate"]), ls=ls, color=col,
                    label=f"T (fold {k}: train {P[k]['features']['train_years'][0]}-"
                          f"{P[k]['features']['train_years'][-1]})")
            if k == 3:
                ax.scatter(kx, 100 * np.array(t["rate_raw"]), s=8, color="C0", alpha=.6,
                           label="raw bin rate (fold 3)")
        ax.set_title(f"{LABEL[c]}  [exp. sign {'+' if signs[c] > 0 else '-'}]", fontsize=9)
        ax.set_ylabel("default rate %")
        if c in ("ar_days", "ap_days", "interest_coverage", "log_assets"):
            ax.set_xscale("symlog")
        t3 = p3["transforms"][c]
        q = np.nanquantile(Xtr[c], [0.05, 0.5, 0.95])
        Tq = RC.apply_transform(q, t3)
        rows.append({"driver": LABEL[c], "feature": c,
                     "p5 value": fmt(c, q[0]), "T at p5 %": 100 * Tq[0],
                     "median": fmt(c, q[1]), "T at median %": 100 * Tq[1],
                     "p95 value": fmt(c, q[2]), "T at p95 %": 100 * Tq[2],
                     "T min-max %": f"{100 * min(t3['rate']):.2f}-{100 * max(t3['rate']):.2f}",
                     "missing: n / T %": f"{t3['n_missing']} / {100 * t3['missing_rate']:.2f}"})
    for ax in axes.ravel()[n:]:
        ax.axis("off")
    axes.ravel()[0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(OD / "transforms.png", dpi=110)
    plt.close(fig)
    md += ["## 1. Driver curves T_i (ratio -> default rate), all three folds", "",
           "![transforms](transforms.png)", "",
           "Solid red = fold-3 transform (used for 2010 predictions); dashed/dotted = folds 2/1 "
           "(stability across training windows); dots = raw (shrunk, pre-PAV) bin rates. Curves are "
           "flat beyond the outer bin centres, so extreme ratios cannot push the PD further "
           "(outlier neutralisation). Natural units on the x-axis.", "",
           pd.DataFrame(rows).to_markdown(index=False, floatfmt=".2f"), ""]

    # ---------------- 2. coefficients, signs, importance ------------------------------------
    beta = pd.Series(p3["coef"])
    se = pd.Series(p3["se"])
    contrib = Ztr.mul(beta[Ztr.columns], axis=1)
    coef_rows = []
    for k in [c for c in p3["design_columns"] if c != "const"]:
        fold_coefs = [P[f]["coef"].get(k, np.nan) for f in (1, 2, 3)]
        coef_rows.append({
            "term": k, "expected sign": "+" if k.startswith("T_") else "n/a (vs ref. C)",
            "coef (fold 3)": beta[k], "SE": se[k], "z": beta[k] / se[k],
            "actual sign": "+" if beta[k] > 0 else "-",
            "agrees": ("yes" if beta[k] > 0 else "NO") if k.startswith("T_") else "",
            "coef fold 1 / 2": " / ".join("dropped" if np.isnan(v) else f"{v:.3f}" for v in fold_coefs[:2]),
            "importance: SD of contribution (train)": contrib[k].std()})
    cdf = pd.DataFrame(coef_rows)
    cdf.to_csv(OD / "explain_coefficients.csv", index=False)
    imp = cdf[cdf.term.str.startswith("T_")].sort_values("importance: SD of contribution (train)",
                                                         ascending=False)
    dropped = {f: [d["term"] for d in P[f]["dropped"]] for f in (1, 2, 3)}
    md += ["## 2. Probit coefficients (fold 3), expected vs actual sign, importance", "",
           "Expected sign for every T_i is + (T_i is already a PD-scale measure). Industry "
           "indicators are relative to manufacturing (ATECO C, the largest training level). "
           "Importance = standard deviation of beta_i * Phi^-1(T_i) across training rows (how much "
           "the driver moves the probit index across firms).", "",
           cdf.to_markdown(index=False, floatfmt=".4f"), "",
           f"Dropped in-window by the sign rule (coef <= 0, most negative z first): {dropped}. "
           "Both dropped terms are explained in `experiments/riskcalc/decisions.md` (D-041).", "",
           "Driver ranking by importance: " + ", ".join(f"{LABEL[t[2:]]}" for t in imp.term), ""]

    # ---------------- 3. final transform F --------------------------------------------------
    F = p3["final"]
    grid = np.linspace(np.quantile(s_tr, 0.0005), np.quantile(s_tr, 0.9995), 300)
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(grid, 100 * RC.apply_final_transform(grid, F), label="F (PAV + interpolation)")
    ax.plot(grid, 100 * norm.cdf(grid), "--", label="Phi(index) (raw probit)")
    ax.scatter(F["knots_index"], 100 * np.array(F["knots_pd"]), s=10, color="k", label="F knots")
    ax.set_yscale("log"), ax.set_xlabel("probit index"), ax.set_ylabel("PD %"), ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(OD / "final_transform.png", dpi=110)
    plt.close(fig)
    md += ["## 3. Final transform F (probit index -> PD)", "", "![F](final_transform.png)", "",
           f"F has {F['n_blocks']} monotone knots fitted on the training window; beyond the outer "
           "knots it continues with slope 1 on the probit scale. F corrects the shape of the "
           "probit's link in-window; it does NOT move the level to the test year's default rate "
           "(that is the calibration-specialist's central-tendency question).", ""]

    # ---------------- 4. reason codes for three test firms ----------------------------------
    Xte = B.transform(te, p3["features"])
    Zte, s_te = RC.index_riskcalc(te, p3, X=Xte)
    pd_te = RC.apply_final_transform(s_te, F)
    med_contrib = contrib.median()
    ind_cols = [c for c in Ztr.columns if c.startswith("ateco_group=")]
    ind_mean = contrib[ind_cols].sum(axis=1).mean()
    complete = Xte[ratios].notna().all(axis=1).to_numpy()
    order = np.argsort(pd_te)
    picks = {}
    for name, q in (("low", 0.10), ("mid", 0.50), ("high", 0.99)):
        target = np.quantile(pd_te, q)
        cand = np.flatnonzero(complete)
        picks[name] = cand[np.argmin(np.abs(pd_te[cand] - target))]
    md += ["## 4. Reason codes for three 2010 test firms (low / mid / high PD)", "",
           "For each driver we recompute the PD with that driver's contribution set to the "
           "training-median firm's contribution (all else unchanged). The difference is the "
           "driver's effect on this firm's PD. Industry is compared with the training-average "
           "industry effect. Firms are anonymised by row_id; the realised outcome is not shown.", ""]
    ex_rows = []
    for name, i in picks.items():
        own = Zte.iloc[i].mul(beta[Zte.columns])
        lines = []
        for c in ratios:
            delta_s = own[f"T_{c}"] - med_contrib[f"T_{c}"]
            p_neutral = float(RC.apply_final_transform(np.array([s_te[i] - delta_s]), F)[0])
            med_val = float(np.nanmedian(Xtr[c]))
            lines.append((c, p_neutral, pd_te[i] - p_neutral, fmt(c, Xte[c].iloc[i]), fmt(c, med_val)))
        ind = Xte["ateco_group"].iloc[i]
        d_ind = own[ind_cols].sum() - ind_mean
        p_neu_ind = float(RC.apply_final_transform(np.array([s_te[i] - d_ind]), F)[0])
        lines.append(("industry", p_neu_ind, pd_te[i] - p_neu_ind, f"ATECO section group {ind}", "average"))
        lines.sort(key=lambda r: -abs(r[2]))
        md += [f"### Example {name}-PD firm (row_id {int(te.row_id.iloc[i])}, PD {100 * pd_te[i]:.2f}%, "
               f"percentile {100 * (np.searchsorted(np.sort(pd_te), pd_te[i]) / len(pd_te)):.0f} of 2010)", ""]
        for c, pn, dd, v, mv in lines[:4]:
            verb = "raised" if dd > 0 else "lowered"
            if c == "industry":
                md.append(f"- Being in {v} (rather than the average industry) {verb} this firm's PD "
                          f"from {100 * pn:.2f}% to {100 * pd_te[i]:.2f}% ({100 * dd:+.2f} pp).")
                continue
            md.append(f"- {LABEL[c]} of {v} (typical firm: {mv}) {verb} this firm's PD from "
                      f"{100 * pn:.2f}% to {100 * pd_te[i]:.2f}% ({100 * dd:+.2f} pp).")
        md.append("")
        for c, pn, dd, v, mv in lines:
            ex_rows.append({"example": name, "row_id": int(te.row_id.iloc[i]), "pd": pd_te[i],
                            "driver": c, "value": v, "typical": mv, "pd_if_typical": pn,
                            "delta_pp": 100 * dd})
    pd.DataFrame(ex_rows).to_csv(OD / "reason_codes_examples.csv", index=False)
    md += ["Effects are not additive in PD units (F and Phi are non-linear); they are additive on "
           "the probit index.", ""]

    # ---------------- 5. reusability checks --------------------------------------------------
    oot = pd.read_parquet(OD / "oot_predictions.parquet").query("fold == 3")
    m = oot.set_index("row_id").loc[te.row_id, "pd"].to_numpy()
    p_file = RC.predict_riskcalc(te, RC.load_params(OD / "params_fold3.json"))
    sub = te.iloc[:300]
    one = np.array([RC.predict_riskcalc(sub.iloc[[j]], p3)[0] for j in range(len(sub))])
    messy = te.iloc[:5].copy().astype(object)
    messy.loc[messy.index[0], "asst_tot"] = "NA"
    messy.loc[messy.index[1], "ateco_sector"] = "99.9"      # unseen category
    messy.loc[messy.index[2], "profit"] = ""
    messy.loc[messy.index[3], "eqty_tot"] = "n.a."
    messy = messy.drop(columns=["cash_and_equiv"])         # a whole column missing
    pm = RC.predict_riskcalc(messy, p3)
    md += ["## 5. Reusability / harness readiness checks", "",
           f"- params JSON round trip vs stored OOT predictions (fold 3, {len(te):,} rows): max |diff| = "
           f"{np.max(np.abs(p_file - m)):.2e}",
           f"- one-row-at-a-time vs batch on 300 rows: max |diff| = {np.max(np.abs(one - p_file[:300])):.2e}",
           f"- messy input (\"NA\", \"\", \"n.a.\", unseen ATECO, dropped column): PDs = "
           f"{', '.join(f'{v:.4f}' for v in pm)} (all in (0,1): {bool(np.all((pm > 0) & (pm < 1)))})",
           "- Estimation for the harness: `riskcalc.fit_and_save(train_rows, path)` (RC-03 config "
           "= `riskcalc.BEST_CONFIG`); prediction: `riskcalc.predict_riskcalc(df, load_params(path))`.",
           "- Prediction complexity: O(n * (p log K + m)) — n rows, p = 10 transforms with K <= 50 "
           "knots (binary search), m = 12 indicator columns, plus one O(log B) lookup in F "
           f"(B = {F['n_blocks']} knots). Memory O(n * (p + m)).", ""]
    (OD / "explain.md").write_text("\n".join(md))
    print("\n".join(md[-8:]))


if __name__ == "__main__":
    main()
