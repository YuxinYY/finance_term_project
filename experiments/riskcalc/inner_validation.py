"""Inner, time-ordered validation inside the fold-3 training window (train fs_year 2007-2008,
validate fs_year 2009). fs_year 2010 (fold-3 test) is never read. Variants of RC-03.

    python experiments/riskcalc/inner_validation.py  -> experiments/riskcalc/inner_validation.md
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))
import riskcalc as RC  # noqa: E402
from run import EXPERIMENTS  # noqa: E402
from src.common import metrics as M  # noqa: E402

BASE = {**RC.DEFAULT_CONFIG, **EXPERIMENTS["RC-03"]["config"]}
VARIANTS = {
    "RC-03 (base)": {},
    "+ legal_group + macro_area": {"categoricals": ["ateco_group", "legal_group", "macro_area"]},
    "no industry indicators": {"categoricals": []},
    "logit link": {"link": "logit"},
    "K <= 20 bins": {"max_bins": 20},
    "K <= 100 bins (min 15 defaults/bin)": {"max_bins": 100, "min_defaults_per_bin": 15},
    "no monotone (PAV off) in T_i": {"monotone": False},
    "prior 10 pseudo-defaults": {"prior_defaults": 10.0},
    "F = identity (raw probit)": {"_F_identity": True},
}


def main():
    panel = pd.read_parquet(ROOT / "data/interim/panel.parquet",
                            filters=[("fs_year", "in", [2007, 2008, 2009])])
    ok = panel[panel.label_status == "ok"]
    tr, va = ok[ok.fs_year <= 2008], ok[ok.fs_year == 2009]
    rows = []
    for name, v in VARIANTS.items():
        cfg = {**BASE, **{k: x for k, x in v.items() if not k.startswith("_")}}
        params = RC.fit_riskcalc(tr, cfg)
        if v.get("_F_identity"):
            _, s = RC.index_riskcalc(va, params)
            p = np.clip(RC._link_inv(s, cfg["link"]), RC.PD_FLOOR, RC.PD_CAP)
        else:
            p = RC.predict_riskcalc(va, params)
        y = va["y"].to_numpy()
        c = M.calibration_slope_intercept(y, p)
        rows.append({"variant": name, "auc": M.auc(y, p), "log_loss": M.log_loss(y, p),
                     "brier": M.brier(y, p), "mean_pd": p.mean(), "observed_dr": y.mean(),
                     "cal_slope": c["cal_slope"],
                     "terms": len(params["design_columns"]) - 1,
                     "dropped": ", ".join(d["term"] for d in params["dropped"]) or "-"})
        print(rows[-1], flush=True)
        if name == "logit link":
            pl = p
        if name == "RC-03 (base)":
            pb = p
    df = pd.DataFrame(rows)
    rho = np.corrcoef(pb, pl)[0, 1]
    from scipy.stats import spearmanr
    md = ["# RiskCalc inner validation (train fs_year 2007-2008 -> validate 2009; inside fold-3 window)",
          "", "Generated by `experiments/riskcalc/inner_validation.py`. fs_year 2010 never read. "
          "Note: 2009 is also the outer test year of fold 2, so these results may only inform "
          "fold-3 / final-model choices, not fold-1/2 outer scores.", "",
          df.to_markdown(index=False, floatfmt=".4f"), "",
          f"Probit vs logit PD on the validation rows: Pearson {rho:.4f}, Spearman "
          f"{spearmanr(pb, pl).statistic:.4f}.", ""]
    (HERE / "inner_validation.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
