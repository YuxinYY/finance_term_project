"""Run RiskCalc-style experiments on the frozen walk-forward folds.

    python experiments/riskcalc/run.py RC-01 [RC-02 ...]

Writes experiments/riskcalc/<exp_id>/{oot_predictions.parquet, config.json, metrics.md,
train_log.md, params_fold<k>.json, coefficients.csv}.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))
import riskcalc as RC  # noqa: E402
from src.common import metrics as M  # noqa: E402
from src.features import build as B  # noqa: E402

CORE10 = list(RC.DEFAULT_CONFIG["ratios"])
EXPERIMENTS = {
    "RC-01": {"desc": "RiskCalc v1: 10 core ratios (T_i = monotone shrunk binned default rate, "
                      "probit scale) + ateco_group indicators; probit; F = PAV on index",
              "parent": "-", "config": {}},
    "RC-02": {"desc": "RC-01 + debt-split block ratios bank_debt_ratio, ap_days (15.7% missing as a "
                      "block; missing gets its own empirical default rate inside T_i) -> tests H2",
              "parent": "RC-01",
              "config": {"ratios": CORE10 + ["bank_debt_ratio", "ap_days"]}},
    "RC-03": {"desc": "RC-02 candidate set + in-window sign selection: any T_i with probit coef <= 0 "
                      "in the fold's own training fit is dropped and the probit refitted",
              "parent": "RC-02",
              "config": {"ratios": CORE10 + ["bank_debt_ratio", "ap_days"],
                         "drop_nonpositive": True}},
}


def load():
    panel = pd.read_parquet(ROOT / "data/interim/panel.parquet")
    splits = json.load(open(ROOT / "data/splits/walkforward.json"))
    tr = pd.read_parquet(ROOT / "data/splits/walkforward_test_rows.parquet")
    return panel, splits, tr


def metrics_md(oot: pd.DataFrame, title: str) -> str:
    out = [f"# {title}: out-of-time metrics (src/common/metrics.py)", "",
           "Generated by `experiments/riskcalc/run.py`. Diagnostic only; the referee's scorecard is "
           "authoritative. AR = 2*AUC - 1. Brier = overall probability accuracy (not a calibration "
           "measure, R-16 p. 32). Calibration-in-the-large = mean PD vs observed default rate.", ""]
    s = M.score(oot["y"], oot["pd"], oot["test_year"].astype(str))
    s2 = M.score(oot["y"], oot["pd"], np.where(oot["firm_seen_in_train"], "seen", "new"))
    s = pd.concat([s, s2[s2.group != "ALL"]])
    cols = ["group", "n", "defaults", "auc", "ar", "log_loss", "brier", "mean_pd", "observed_dr",
            "ratio_obs_to_pred", "binom_pvalue", "cal_intercept", "cal_slope"]
    out += ["## Pooled, per test year, seen vs new firms", "",
            s[cols].to_markdown(index=False, floatfmt=".4f"), ""]
    d = M.decile_table(oot["y"], oot["pd"])
    out += ["## Decile table (pooled)", "", d.to_markdown(index=False, floatfmt=".4f"), ""]
    return "\n".join(out), s


def run(exp_id: str, panel, splits, testrows):
    spec = EXPERIMENTS[exp_id]
    odir = HERE / exp_id
    odir.mkdir(exist_ok=True)
    cfg = {**RC.DEFAULT_CONFIG, **spec["config"]}
    preds, logs, coefs = [], [], []
    for f in splits["folds"]:
        t0 = time.time()
        k = f["fold"]
        tr = panel[panel.fs_year.isin(f["train_years"]) & (panel.label_status == "ok")]
        te_ids = testrows.loc[testrows.fold == k]
        te = panel.set_index("row_id").loc[te_ids.row_id].reset_index()
        assert len(tr) == f["n_train"] and len(te) == f["n_test"]
        assert tr.fs_year.max() < f["test_year"]
        params = RC.fit_riskcalc(tr, cfg)
        RC.save_params(params, odir / f"params_fold{k}.json")
        p = RC.predict_riskcalc(te, params)
        assert np.all((p > 0) & (p < 1)) and len(p) == len(te)
        preds.append(pd.DataFrame({"row_id": te.row_id.values, "fold": k, "pd": p}))
        for c in params["design_columns"]:
            coefs.append({"fold": k, "term": c, "coef": params["coef"][c], "se": params["se"][c],
                          "z": params["coef"][c] / params["se"][c]})
        logs.append({"fold": k, "train_years": f["train_years"], "n_train": params["n_train"],
                     "train_defaults": params["train_defaults"], "base_rate": params["base_rate"],
                     "n_bins": params["n_bins"], "converged": params["converged"],
                     "llf": params["llf"],
                     "dropped_in_window": ", ".join(f"{d['term']} (z={d['z']:.2f})" for d in params["dropped"]) or "-", "F_blocks": params["final"]["n_blocks"],
                     "seconds": round(time.time() - t0, 1)})
        print(exp_id, logs[-1], flush=True)
    oot = pd.concat(preds, ignore_index=True)
    oot.to_parquet(odir / "oot_predictions.parquet", index=False)
    json.dump({"exp_id": exp_id, "agent": "challenger-riskcalc", "date": "2026-10-31",
               "description": spec["desc"], "parent": spec["parent"], "model_config": cfg,
               "feature_version": B.VERSION, "model_version": RC.VERSION,
               "splits": "data/splits/walkforward.json v1",
               "label": "y (primary, D-002/D-009)",
               "pre_declared": "K bins = clip(train_defaults // 30, 10, 50); prior 2 pseudo-defaults; "
                               "F with 100 index bins. No tuning on test years; fold 1 (one training "
                               "year) uses the same pre-declared defaults."},
              open(odir / "config.json", "w"), indent=1)
    cdf = pd.DataFrame(coefs)
    cdf.to_csv(odir / "coefficients.csv", index=False)
    # metrics
    ev = oot.merge(panel[["row_id", "y"]], on="row_id").merge(
        testrows[["row_id", "fold", "test_year", "firm_seen_in_train"]], on=["row_id", "fold"])
    assert len(ev) == len(oot)
    md, s = metrics_md(ev, exp_id)
    (odir / "metrics.md").write_text(md)
    s.to_csv(odir / "metrics_summary.csv", index=False)
    # train log
    signs = B.expected_signs()
    lines = [f"# {exp_id} train log", "", spec["desc"], "",
             "## Per-fold fit", "", pd.DataFrame(logs).to_markdown(index=False, floatfmt=".4f"), "",
             "## Probit coefficients by fold (coef, SE, z)", "",
             "Transformed ratios enter as Phi^-1(T_i(x)), a PD-scale measure: expected sign + for "
             "every T_i (the ratio's own direction is inside T_i). Indicators are vs the reference "
             "level (largest training level).", ""]
    piv = cdf.pivot_table(index="term", columns="fold", values=["coef", "se"]).round(4)
    piv.columns = [f"{a}_f{b}" for a, b in piv.columns]
    piv = piv.reindex(pd.unique(cdf.term))
    neg = [t for t in piv.index if t.startswith("T_") and (piv.filter(like="coef").loc[t] <= 0).any()]
    lines += [piv.to_markdown(), "",
              f"Sign violations among T_i (coef <= 0 in any fold): {neg if neg else 'none'}", "",
              "Ratio selection: fixed economically balanced set from FEATURE_SPEC (same in every "
              "fold; only bins, rates and coefficients are re-estimated per fold).", ""]
    (odir / "train_log.md").write_text("\n".join(lines))
    print(s[["group", "n", "auc", "log_loss", "brier", "mean_pd", "observed_dr", "cal_slope"]])
    print("negative T coefs:", neg)
    return oot, params


if __name__ == "__main__":
    panel, splits, testrows = load()
    for e in sys.argv[1:]:
        run(e, panel, splits, testrows)
