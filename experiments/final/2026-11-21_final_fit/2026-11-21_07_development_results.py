"""One generated report of every development comparison (which training beat what), built only from result files.
Output: reports/final_model/2026-11-21_development_results.md
"""
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
G = REPO / "experiments/gbm/2026-11-20_grid75"
OUT = REPO / "reports/final_model/2026-11-21_development_results.md"


def md(df, **k):
    return df.to_markdown(index=False, **k) + "\n"


grid = pd.read_csv(G / "grid_results.csv")
summ = pd.read_csv(G / "grid_summary.csv")
lvl = pd.read_csv(G / "level_check.csv")
boot = pd.read_csv(G / "bootstrap_free_minus_mono.csv")
seed = pd.read_csv(G / "seed_check.csv")
abl = pd.read_csv(G / "ablation_summary.csv")
ablr = pd.read_csv(G / "ablation_results.csv")
sel = json.loads((G / "selection.json").read_text())
fin = json.loads((HERE / "final_insample_summary.json").read_text())
var = pd.read_csv(HERE / "variants/variants_summary.csv")
YEARS = {"round 01": ("2007", "2008", "2009"), "round 02": ("2007-2008", "2009", "2010"), "round 03": ("2007-2009", "2010", "2011 (lockbox)")}

L = []
L += ["# Development results: which training beat what (generated 2026-11-21)\n\n",
      "Generated by `experiments/final/2026-11-21_final_fit/2026-11-21_07_development_results.py` from the result files in "
      "`experiments/gbm/2026-11-20_grid75/` and `experiments/final/2026-11-21_final_fit/`. Every number below comes from those files.\n\n"]

L += ["## 1. Setup\n\n",
      "- Data: Chloe's 11.20 files, 75 VIF-selected features, 5-month label (D-151); audited clean (D-156).\n",
      "- Walk-forward rounds (train / validation / test):\n\n",
      md(pd.DataFrame([dict(round=r, train=a, validation=b, test=c) for r, (a, b, c) in YEARS.items()])),
      "- Every round: preprocessing and model fitted on train only; early stopping on validation AUC; test years reported only, never "
      "used to choose (round-3 test FY2011 is the lockbox).\n",
      "- Selection rule (D-158, fixed before results): mean validation AUC over the 3 rounds; settings within 0.001 AUC tie; ties go to "
      "lower mean validation log loss, then the simpler setting.\n",
      f"- Grid: {grid.setting.nunique()} of 288 settings run in both modes (monotone with the D-157 sign table, unconstrained) x 3 rounds "
      f"= {len(grid)} fits, learning rate 0.05.\n\n"]

L += ["## 2. Grid winners\n\n"]
for mode in ("mono", "free"):
    s = summ[summ["mode"] == mode].sort_values("val_auc", ascending=False).head(10)
    L += [f"### Top 10 settings, {'monotone' if mode == 'mono' else 'unconstrained'} (mean over 3 rounds)\n\n",
          md(s[["setting", "val_auc", "val_auc_min", "val_logloss", "test_auc", "test_logloss", "iter_max"]].round(5)), "\n"]
L += [f"Chosen by the rule: monotone `{sel['settings']['mono']}`, unconstrained `{sel['settings']['free']}` (the same setting).\n\n"]

L += ["### Which hyperparameters mattered (mean validation AUC over all settings with that value, both modes)\n\n"]
for h in ["num_leaves", "min_child_samples", "feature_fraction", "bagging_fraction", "lambda_l2"]:
    t = summ.groupby([h, "mode"]).val_auc.mean().unstack().round(5).reset_index()
    L += [f"**{h}**\n\n", md(t), "\n"]

L += ["## 3. The two winners round by round\n\n",
      "Validation = used for selection; test = reported only. Raw model PDs (before the level step).\n\n",
      md(lvl[["mode", "round", "split", "year", "auc", "ll_raw", "dr", "mean_pd_raw", "obs_pred_raw", "best_iter"]].round(5)),
      "\nobs/pred > 1 = the model under-predicts the year's default rate: true in every validation year for both modes; "
      "the level step of the final model (prior shift to tau, D-072) addresses this.\n\n"]

L += ["## 4. Monotone vs unconstrained head to head\n\n",
      "### Paired bootstrap, unconstrained minus monotone (validation, 500 draws)\n\n", md(boot.round(5)),
      "\n### Seed robustness (full-data binning, seeds 1-3, validation)\n\n"]
sp = seed.pivot_table(index=["round", "seed"], columns="mode", values="auc").reset_index()
sp["free_minus_mono"] = sp["free"] - sp["mono"]
L += [md(sp.round(5)), f"\nUnconstrained ahead in {(sp.free_minus_mono > 0).sum()} of {len(sp)} runs; mean gap {sp.free_minus_mono.mean():+.5f} AUC.\n\n"]

L += ["## 5. Constraint ablation (winner setting, 2 seeds x 3 rounds, validation)\n\n",
      "`rel_<feature>` = full monotone with that one constraint released; `lit13` = only the 13 direct-literature constraints; "
      "`mono_m3` = monotone minus quick_ratio, int_coverage, operating_cash_flow_margin (data-driven, information only). "
      "Differences below about 0.0003 AUC are seed noise.\n\n",
      md(abl.rename(columns={"config": "configuration"}).round(5)),
      "\nPer round (mean of 2 seeds):\n\n",
      md(ablr[ablr.config.isin(["mono", "free", "lit13", "rel_cur_debt_ratio", "rel_quick_ratio"])]
         .groupby(["config", "round"]).auc.mean().unstack().round(5).reset_index()), "\n"]

L += ["## 6. Final models fitted on all FY2007-2011 rows (in-sample, sanity only)\n\n",
      "No held-out year exists for these by design; their out-of-sample evidence is Sections 2-5. All share the same frozen "
      "preprocessing and level recipe (prior shift to tau 1.4641%, floor 0.03%, cap 99%).\n\n"]
rows = [dict(variant="free (main bundle)", n_constraints=0, trees=210, insample_auc=fin["insample_auc"],
             insample_logloss_raw=fin["insample_logloss_raw"], mean_final_pd=fin["mean_final_pd"], max_pd=fin["max_pd"],
             bundle="harness/2026-11-21_Turquoise_harness.zip")]
for _, r in var.iterrows():
    rows.append(dict(variant=r.variant, n_constraints=r.n_constraints, trees=r.trees, insample_auc=r.insample_auc,
                     insample_logloss_raw=r.insample_logloss_raw, mean_final_pd=r.mean_final_pd, max_pd=r.max_pd,
                     bundle=f"harness/2026-11-21_variants/2026-11-21_Turquoise_harness_{r.variant}.zip"))
L += [md(pd.DataFrame(rows).round(5)),
      "\nIn-sample AUC rewards flexibility (more trees, fewer constraints) and is not evidence of out-of-sample quality.\n\n"]

L += ["## 7. Where the rest is\n\n",
      "- Grid report with level check and sign check: `experiments/gbm/2026-11-20_grid75/2026-11-20_grid75_report.md`\n",
      "- Sign table, literature, conflicts, SHAP sign check, recommendation: `reports/features/2026-11-21_sign_table_monotone_decision.md`\n",
      "- Final-model SHAP: `reports/final_model/2026-11-21_shap_summary.md`\n",
      "- Harness tests: `reports/harness/2026-11-21_harness_test_report.md`\n",
      "- Decisions: `docs/DECISION_LOG.md` D-156 to D-161\n"]
OUT.write_text("".join(L))
print(OUT)
